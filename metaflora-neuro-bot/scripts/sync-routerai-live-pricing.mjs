import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, 'src', 'routerai-live-pricing.js');
const ENDPOINT = 'https://routerai.ru/api/v1/models';
const MODEL_ID = /^[A-Za-z0-9][A-Za-z0-9._/-]{1,160}$/u;
const PRICE_FIELD = /^[a-z][a-z0-9_]{0,63}$/u;

function validatedPrices(pricing) {
  if (!pricing || typeof pricing !== 'object' || Array.isArray(pricing)) return null;
  const normalized = Object.fromEntries(Object.entries(pricing)
    .filter(([key, value]) => PRICE_FIELD.test(key) && Number.isFinite(value) && value >= 0)
    .sort(([left], [right]) => left.localeCompare(right)));
  return Object.keys(normalized).length > 0 ? normalized : null;
}

const response = await fetch(ENDPOINT, {
  signal: AbortSignal.timeout(30_000)
});
if (!response.ok) throw new Error(`RouterAI model catalog returned HTTP ${response.status}.`);

const payload = await response.json();
if (!Array.isArray(payload?.data)) throw new Error('RouterAI model catalog payload is invalid.');

const entries = payload.data
  .map(({ id, pricing }) => [id, validatedPrices(pricing)])
  .filter(([id, pricing]) => MODEL_ID.test(id) && pricing !== null)
  .sort(([left], [right]) => left.localeCompare(right));

if (entries.length < 400) {
  throw new Error(`RouterAI model catalog is unexpectedly incomplete: ${entries.length} price records.`);
}

const checkedAt = new Date().toISOString().slice(0, 10);
const snapshot = Object.fromEntries(entries);
const source = `// Generated by scripts/sync-routerai-live-pricing.mjs from ${ENDPOINT}.\n// Do not edit by hand; this endpoint is public and contains no credentials.\nexport const ROUTERAI_LIVE_PRICING_CHECKED_AT = ${JSON.stringify(checkedAt)};\n\nconst prices = ${JSON.stringify(snapshot, null, 2)};\n\nexport const ROUTERAI_LIVE_PRICING = Object.freeze(Object.fromEntries(\n  Object.entries(prices).map(([providerModelId, pricing]) => [\n    providerModelId,\n    Object.freeze({ ...pricing })\n  ])\n));\n`;

await mkdir(path.dirname(TARGET), { recursive: true });
await writeFile(TARGET, source, 'utf8');
process.stdout.write(`Wrote ${entries.length} RouterAI live price records to ${TARGET}.\n`);
