function card(description, instruction, inputs, settings, highlights) {
  const invalidHighlight = highlights.find((highlight) => !description.includes(highlight));
  if (invalidHighlight) {
    throw new Error(`Model card highlight is not an exact description substring: ${invalidHighlight}`);
  }
  return Object.freeze({
    description,
    instruction,
    inputs,
    settings,
    highlights: Object.freeze(highlights)
  });
}

