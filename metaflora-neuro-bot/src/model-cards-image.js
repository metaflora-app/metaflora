const commonImageFormats = ['jpeg', 'png', 'webp'];
const setting = (defaultValue, values) => ({ defaultValue, values });

const directImageCard = (name, description, {
  editable = true,
  vector = false,
  fullDescription,
  highlights,
  supportsMultipleImages = true,
  supportsOutputFormat = true
} = {}) => ({
  description: fullDescription ?? `${name} ${description} В карточке можно выбрать пропорции кадра${supportsOutputFormat ? ' и формат результата' : ''}${supportsMultipleImages ? ', а также число вариантов' : ''} без лишних технических настроек.`,
  highlights: highlights ?? [name, 'изображения'],
  instruction: editable
    ? 'Опиши изображение или приложи референс и перечисли нужные изменения.'
    : 'Опиши сюжет, композицию, стиль и точные надписи.',
  inputs: editable ? ['text', 'image'] : ['text'],
  settings: {
    aspect_ratio: setting('1:1', ['auto', '1:1', '4:3', '3:4', '16:9', '9:16', '3:2', '2:3']),
    ...(supportsMultipleImages ? { num_images: setting('1', ['1', '2', '3', '4']) } : {}),
    ...(supportsOutputFormat ? {
      output_format: setting(vector ? 'svg' : 'png', vector ? ['svg'] : commonImageFormats)
    } : {})
  }
});

