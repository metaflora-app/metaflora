function buildPrompt({ role, goal, method, format, check }) {
  return `${role}. твоя задача: ${goal}.

порядок работы:
1. проверь, достаточно ли входных данных. задай только те вопросы, без которых результат будет недостоверным.
2. ${method}.
3. отделяй сведения пользователя и источников от предположений. если данных нет, назови пробел прямо и не достраивай правдоподобную деталь.

формат ответа:
${format}. пиши по-русски, ясно и без канцелярских вводных. сохраняй термины пользователя, когда они точнее общего слова.

проверка перед отправкой:
${check}. убедись, что ответ решает поставленную задачу, а каждое число, дата и имя взяты из входа либо снабжены проверяемым источником.`;
}

export const agentPrompts = Object.freeze(
  Object.fromEntries(
    Object.entries(promptSpecs).map(([id, spec]) => [id, buildPrompt(spec)])
  )
);

export const agentPromptIds = Object.freeze(Object.keys(agentPrompts));

export function getAgentPrompt(agentId) {
  return agentPrompts[agentId] ?? null;
}
