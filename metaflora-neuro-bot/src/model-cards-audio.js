function settings(profile = {}) {
  return Object.freeze(
    Object.fromEntries(
      Object.entries(profile).map(([key, value]) => [
        key,
        Object.freeze({
          defaultValue: value.defaultValue,
          values: Object.freeze(value.values)
        })
      ])
    )
  );
}

function card(description, instruction, inputs, profileSettings, highlights) {
  if (highlights.some((highlight) => !description.includes(highlight))) {
    throw new Error('Every audio card highlight must be an exact description substring.');
  }

  return Object.freeze({
    description,
    instruction,
    inputs,
    settings: settings(profileSettings),
    highlights: Object.freeze(highlights)
  });
}

